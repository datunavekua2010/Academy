export const colorByKey = (key: string): LogicColor => {
  const found = LOGIC_COLORS[key];
  if (!found) throw new Error(`unknown color "${key}"`);
  return found;
};

/**
 * Builds a color sequence with a missing blank at the end or middle.
 */
export const colorSequenceVisual = (colors: LogicColor[], blankIndex = colors.length - 1): string => {
  return colors
    .map((c, i) => (i === blankIndex ? '❓' : c.emoji))
    .join('  ');
};

export const colorSequenceWords = (colors: LogicColor[], blankIndex = colors.length - 1): string => {
  return colors
    .map((c, i) => (i === blankIndex ? '___' : c.name))
    .join(', ');
};

