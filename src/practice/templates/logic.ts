/* ================================================================== *\
 * Balance scales (U16.3)
 * ================================================================== */

export interface BalanceScale {
  leftCount: number;
  rightCount: number;
  leftItem: string;
  rightItem: string;
  leftEmoji: string;
  rightEmoji: string;
  balanced: boolean;
  heavierSide: 'left' | 'right' | 'equal';
  difference: number;
}

export const createBalanceScale = (
  leftCount: number,
  rightCount: number,
  itemName = 'კუბიკი',
  emoji = '🧊',
): BalanceScale => {
  const balanced = leftCount === rightCount;
  const heavierSide = leftCount > rightCount ? 'left' : rightCount > leftCount ? 'right' : 'equal';
  const difference = Math.abs(leftCount - rightCount);
  return {
    leftCount,
    rightCount,
    leftItem: itemName,
    rightItem: itemName,
    leftEmoji: emoji,
    rightEmoji: emoji,
    balanced,
    heavierSide,
    difference,
  };
};

/**
 * Draws a balance scale with left and right pans.
 *
 * Example:
 *   მარცხენა მხარე: 🧊 🧊 🧊
 *   ═════════ ▲ ═════════
 *   მარჯვენა მხარე: 🧊
 */
export const drawBalanceScale = (scale: BalanceScale): string => {
  const leftTokens = Array.from({ length: scale.leftCount }, () => scale.leftEmoji).join(' ');
  const rightTokens = Array.from({ length: scale.rightCount }, () => scale.rightEmoji).join(' ');

  if (scale.balanced) {
    return `[ ${leftTokens} ]  ═══ ▲ ═══  [ ${rightTokens} ]`;
  }
  if (scale.heavierSide === 'left') {
    return `[ ${leftTokens} ] (დაბლა)\n   \\═══ ▲ ═══/\n             [ ${rightTokens} ] (მაღლა)`;
  }
  return `             [ ${leftTokens} ] (მაღლა)\n   /═══ ▲ ═══\\\n[ ${rightTokens} ] (დაბლა)`;
};

/* ================================================================== *\
 * Parsers and verification helpers for tests
 * ================================================================== */

export const parseColorSequenceVisual = (visual: string): { emojis: string[]; targetIndex: number; totalCount: number } => {
  const parts = visual.split(/\s+/).filter((p) => p.length > 0);
  const targetIndex = parts.findIndex((p) => p === '❓');
  return { emojis: parts, targetIndex, totalCount: parts.length };
};

export const parseBalanceVisual = (visual: string): { leftTokens: number; rightTokens: number; balanced: boolean } => {
  const bracketMatches = [...visual.matchAll(/\[([^\]]*)\]/g)];
  if (bracketMatches.length >= 2) {
    const leftInner = bracketMatches[0]![1]!.trim();
    const rightInner = bracketMatches[1]![1]!.trim();
    const leftTokens = leftInner.split(/\s+/).filter((t) => t.length > 0).length;
    const rightTokens = rightInner.split(/\s+/).filter((t) => t.length > 0).length;
    return { leftTokens, rightTokens, balanced: leftTokens === rightTokens };
  }
  return { leftTokens: 0, rightTokens: 0, balanced: false };
};

export const parseBalanceScaleVisual = (visual: string): { leftCount: number; rightCount: number; balanced: boolean } => {
  const res = parseBalanceVisual(visual);
  return { leftCount: res.leftTokens, rightCount: res.rightTokens, balanced: res.balanced };
};
