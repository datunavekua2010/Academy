// PGlite-only synthetic test. No real JWT verification or remote database access.
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
const user='00000000-0000-4000-8000-000000000001';
const other='00000000-0000-4000-8000-000000000002';
const session='00000000-0000-4000-8000-000000000003';
const otherSession='00000000-0000-4000-8000-000000000004';
const state=n => n.repeat(64);
const nonce='A'.repeat(43), verifier='V'.repeat(43), cookie=state('c');
try {
  await db.exec(`create role anon; create role authenticated; create role service_role;
  create schema auth; create schema academy_private;
  revoke all on schema academy_private from public; grant usage on schema academy_private to authenticated;
  create table auth.users(id uuid primary key);
  create table auth.sessions(id uuid primary key,user_id uuid references auth.users(id),not_after timestamptz);
  create table auth.identities(user_id uuid references auth.users(id),provider text,provider_id text);
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
  create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
  create function academy_private.role_session_method_allows(text) returns boolean language sql stable as $$ select (auth.jwt()->'amr') = '[{"method":"oauth"}]'::jsonb $$;
  grant usage on schema auth to authenticated; grant execute on function auth.uid(),auth.jwt() to authenticated;`);
  await db.exec(readFileSync('supabase/review/google-session-proof-candidate.sql','utf8'));
  const q=(sql,args=[])=>db.query(sql,args);
  await q('insert into auth.users(id) values($1),($2)',[user,other]);
  await q('insert into auth.sessions(id,user_id) values($1,$2),($3,$4)',[session,user,otherSession,other]);
  await q("insert into auth.identities(user_id,provider,provider_id) values($1,'google','google-subject'),($2,'google','other-subject')",[user,other]);
  const role=async name=>db.exec(`reset role; set role ${name}`);
  const claims=async (who,sid,method='oauth')=>{
    await q("select set_config('request.jwt.claim.sub',$1,false)",[who]);
    await q("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({session_id:sid,amr:[{method}]})]);
  };
  const current=async()=> (await q('select academy_private.review_google_proof_current() as ok')).rows[0].ok;
  const begin=(who,sid,hash)=>q('select public.review_google_proof_begin($1,$2,$3,$4,$5,$6)',[who,sid,hash,cookie,nonce,verifier]);
  const read=(hash,c)=>q('select * from public.review_google_proof_read($1,$2)',[hash,c]);
  const finish=(hash,n,subject,c=cookie)=>q('select public.review_google_proof_finish($1,$2,$3,$4)',[hash,c,n,subject]);
  await role('authenticated'); await claims(user,session); assert.equal(await current(),false);
  await assert.rejects(()=>begin(user,session,state('a')));
  await assert.rejects(()=>read(state('a'),cookie));
  await assert.rejects(()=>q('select * from academy_private.google_session_proofs'));
  await role('service_role');
  await assert.rejects(()=>begin(user,otherSession,state('a')));
  await begin(user,session,state('e'));
  await begin(user,session,state('a'));
  assert.equal((await read(state('e'),cookie)).rows.length,0);
  assert.equal((await read(state('a'),state('d'))).rows.length,0);
  assert.deepEqual((await read(state('a'),cookie)).rows,[{nonce,code_verifier:verifier}]);
  await assert.rejects(()=>finish(state('a'),nonce,'google-subject',state('d')));
  await assert.rejects(()=>finish(state('a'),'B'.repeat(43),'google-subject'));
  await assert.rejects(()=>finish(state('a'),nonce,'other-subject'));
  await finish(state('a'),nonce,'google-subject');
  await assert.rejects(()=>finish(state('a'),nonce,'google-subject'));
  await role('authenticated'); await claims(user,session); assert.equal(await current(),true);
  await claims(user,otherSession); assert.equal(await current(),false);
  await claims(other,session); assert.equal(await current(),false);
  await claims(user,session,'password'); assert.equal(await current(),false);
  await role('service_role'); await begin(user,session,state('b'));
  for (let i=0;i<5;i++) assert.equal((await read(state('b'),cookie)).rows.length,1);
  assert.equal((await read(state('b'),cookie)).rows.length,0, 'callback reads are bounded');
  await role('postgres'); await q("update academy_private.google_proof_challenges set expires_at=clock_timestamp()-interval '1 second' where state_hash=$1",[state('b')]);
  await role('service_role'); await assert.rejects(()=>finish(state('b'),nonce,'google-subject'));
  for (const id of ['0','1','2','3']) await begin(user,session,state(id));
  await assert.rejects(()=>begin(user,session,state('4')), 'unfinished starts are bounded');
  await role('postgres'); await q("update academy_private.google_proof_challenges set start_window_at=clock_timestamp()-interval '6 minutes' where session_id=$1",[session]);
  await role('service_role'); await begin(user,session,state('4'));
  assert.equal((await read(state('4'),cookie)).rows.length,1, 'new rate window permits a retry');
  await role('postgres'); await q("delete from auth.identities where user_id=$1 and provider='google'",[user]);
  await role('authenticated'); await claims(user,session); assert.equal(await current(),false);
  await role('postgres'); await q("insert into auth.identities values($1,'google','google-subject')",[user]);
  await q('delete from auth.sessions where id=$1',[session]);
  await role('authenticated'); await claims(user,session); assert.equal(await current(),false);
  console.log('Local Google session-proof prototype checks passed; no real OAuth flow or RLS integration tested.');
} finally { await db.close(); }
