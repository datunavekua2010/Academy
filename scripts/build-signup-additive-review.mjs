// Builds a deliberately gated, additive review migration. It is not part of
// supabase/migrations and must not be deployed automatically.
import {readFileSync,writeFileSync} from 'node:fs';
const load = file => readFileSync(`supabase/review/${file}`,'utf8');
const transaction = sql => {
 const start=sql.indexOf('begin;'); const end=sql.lastIndexOf('commit;');
 if(start<0 || end<start) throw Error('Missing transaction markers');
 return sql.slice(start+6,end).trim();
};
const once=(sql,from,to)=>{
 const i=sql.indexOf(from);if(i<0||sql.indexOf(from,i+from.length)>=0)throw Error(`Expected one occurrence: ${from}`);
 return sql.slice(0,i)+to+sql.slice(i+from.length);
};
const role=load('role-signin-method-candidate.sql');
const method=role.slice(role.indexOf('create function academy_private.role_session_method_allows'),role.indexOf('-- This preserves admin behavior'));
if(!method.includes('grant execute on function')) throw Error('Missing method function');
const gated=(sql, signature, gate)=>{
 const index=sql.indexOf(signature); if(index<0)throw Error(`Missing ${signature}`);
 const pos=sql.indexOf('\nbegin\n',index); if(pos<0)throw Error(`Missing body for ${signature}`);
 return sql.slice(0,pos)+sql.slice(pos).replace('\nbegin\n',`\nbegin\n  if not academy_private.signup_release_enabled('${gate}') then raise exception 'Unavailable'; end if;\n`);
};
let proof=transaction(load('google-session-proof-candidate.sql'));
for(const sig of ['create function public.review_google_proof_begin(', 'create function public.review_google_proof_finish('])proof=gated(proof,sig,'proof');
proof=once(proof,'  where s.id=c.session_id and s.user_id=c.user_id','  where academy_private.signup_release_enabled(\'proof\') and s.id=c.session_id and s.user_id=c.user_id');
proof=once(proof,"  select academy_private.role_session_method_allows('parent') and exists (","  select academy_private.signup_release_enabled('proof') and academy_private.role_session_method_allows('parent') and exists (");
let limit=transaction(load('google-proof-ingress-limit-candidate.sql'));
limit=gated(limit,'create function public.review_google_proof_rate_limit(','proof');
let student=gated(transaction(load('student-self-enrollment-candidate.sql')),'create function public.review_student_self_enroll(','enrollment');
let parent=gated(transaction(load('parent-self-enrollment-candidate.sql')),'create function public.review_parent_self_enroll(','enrollment');
let link=transaction(load('parent-link-application-candidate.sql'));
for(const name of ['review_parent_link_request','review_parent_link_my_requests','review_parent_link_cancel','review_admin_parent_link_applications','review_admin_parent_link_decide'])link=gated(link,`create function public.${name}(`,'parent_link');
const header=`-- GENERATED by scripts/build-signup-additive-review.mjs. NOT auto-applied.
-- Forward-only, additive install, fail-closed by default. Does not change any
-- existing authorization policy or role helper; existing sessions remain intact.
-- See docs/signup-integration-status.md before testing, enabling or deploying.
-- Any name collision or missing dependency aborts the complete transaction.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$ begin
  if to_regnamespace('academy_private') is null
     or to_regprocedure('academy_private.lock_role_lifecycle(uuid,text)') is null
     or to_regprocedure('academy_private.has_role(text)') is null
     or to_regprocedure('public.admin_establish_parent_link(uuid,uuid,text)') is null
     or to_regclass('public.profiles') is null or to_regclass('public.user_roles') is null
     or to_regclass('public.student_grades') is null or to_regclass('auth.sessions') is null
     or to_regclass('auth.identities') is null then
    raise exception 'Signup migration prerequisites missing';
  end if;
end $$;
create table academy_private.signup_release_control (
  gate text primary key check (gate in ('proof','authorization','enrollment','parent_link')),
  enabled boolean not null default false
);
insert into academy_private.signup_release_control(gate) values ('proof'),('authorization'),('enrollment'),('parent_link');
alter table academy_private.signup_release_control enable row level security;
revoke all on academy_private.signup_release_control from public,anon,authenticated,service_role;
create function academy_private.signup_release_enabled(p_gate text) returns boolean
language sql stable security definer set search_path='' as $$
  select coalesce((select enabled from academy_private.signup_release_control where gate=p_gate),false)
    and (p_gate not in ('enrollment','parent_link') or
      (coalesce((select enabled from academy_private.signup_release_control where gate='authorization'),false)
       and coalesce((select enabled from academy_private.signup_release_control where gate='proof'),false)));
$$;
revoke all on function academy_private.signup_release_enabled(text) from public,anon,authenticated,service_role;
`;
const cleanup=`
-- Invoked by a trusted operator/scheduler, not browser/service-role clients.
-- Batch limits avoid unbounded locks and don't delete enrollment or link records.
create index google_proof_challenges_expiry on academy_private.google_proof_challenges(expires_at);
create index google_session_proofs_expiry on academy_private.google_session_proofs(expires_at);
create function academy_private.signup_cleanup_expired(p_limit integer default 500)
returns table(challenges bigint,proofs bigint,rate_limits bigint)
language plpgsql security definer set search_path='' as $$
begin
  if p_limit is null or p_limit < 1 or p_limit > 5000 then raise exception 'Invalid batch'; end if;
  with picked as (select state_hash from academy_private.google_proof_challenges where expires_at<statement_timestamp() order by expires_at,state_hash limit p_limit for update skip locked),
    deleted as (delete from academy_private.google_proof_challenges c using picked p where c.state_hash=p.state_hash returning 1)
    select count(*) into challenges from deleted;
  with picked as (select session_id from academy_private.google_session_proofs where expires_at<statement_timestamp() order by expires_at,session_id limit p_limit for update skip locked),
    deleted as (delete from academy_private.google_session_proofs c using picked p where c.session_id=p.session_id returning 1)
    select count(*) into proofs from deleted;
  with picked as (select scope,key_hash from academy_private.google_proof_ingress_limits where window_started_at<statement_timestamp()-interval '1 day' order by window_started_at,scope,key_hash limit p_limit for update skip locked),
    deleted as (delete from academy_private.google_proof_ingress_limits c using picked p where c.scope=p.scope and c.key_hash=p.key_hash returning 1)
    select count(*) into rate_limits from deleted;
  return next;
end; $$;
revoke all on function academy_private.signup_cleanup_expired(integer) from public,anon,authenticated,service_role;
commit;
`;
const path='supabase/review/release/202612120001_signup_additive.sql';
const generated=[header,method,proof,limit,student,parent,link,cleanup].join('\n\n');
if(process.argv.includes('--check')) {
 if(readFileSync(path,'utf8')!==generated) throw Error('Signup migration differs from reviewed source; regenerate and review it');
 console.log('Signup migration matches generator and source.');
} else writeFileSync(path,generated);
