// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { Classrooms } from '../src/teacher/Classrooms';
import { Shell } from '../src/Shell';
const roster = [{ id:'s1', name:'სატესტო პირველი', grade:1 }, { id:'s2', name:'სატესტო მეორე', grade:2 }];
beforeEach(() => { window.location.hash = '#/teacher/interventions'; window.scrollTo = vi.fn(); });
afterEach(() => { cleanup(); window.location.hash = ''; document.body.classList.remove('axiom-cards-printing'); vi.restoreAllMocks(); });
it('integrates in the existing support tab and explicitly marks the non-persistent test state and unavailable invite', async () => {
  render(<Shell />);
  expect(await screen.findByRole('heading', { name: 'კლასების მართვა' })).toBeTruthy();
  expect(screen.getByText(/კლასები მხოლოდ ამ გვერდზე არსებობს და გასვლისას იშლება/)).toBeTruthy();
  expect(screen.getByText(/მოწვევის კოდი და კოდით გაწევრიანება ჯერ არ არის/)).toBeTruthy();
  expect(await screen.findByText('კლასები ჯერ არ არის.')).toBeTruthy();
});
it('creates, updates, assigns, selects, prints, removes and archives without claiming credentials', async () => {
  const print = vi.fn(() => { expect(document.body.classList.contains('axiom-cards-printing')).toBe(true); });
  vi.stubGlobal('print', print);
  const { unmount } = render(<Classrooms client={null} assigned={roster} test />);
  await screen.findByText('კლასები ჯერ არ არის.');
  fireEvent.change(screen.getByLabelText('კლასის სახელი'), { target:{ value:'სატესტო კლასი' } });
  fireEvent.change(screen.getByLabelText('საფეხური (არასავალდებულო)'), { target:{ value:'1' } });
  fireEvent.click(screen.getByRole('button', { name:'კლასის შექმნა' }));
  let room = (await screen.findByText('სატესტო კლასი')).closest('li')!;
  expect(room.textContent).toContain('0 მოსწავლე');
  fireEvent.click(within(room).getByRole('button', { name:'შეცვლა' }));
  fireEvent.change(screen.getByLabelText('კლასის სახელი'), { target:{ value:'შეცვლილი კლასი' } });
  fireEvent.click(screen.getByRole('button', { name:'ცვლილების შენახვა' }));
  room = (await screen.findByText('შეცვლილი კლასი')).closest('li')!;
  fireEvent.click(within(room).getByRole('button', { name:'გახსნა' }));
  await screen.findByText('კლასში მოსწავლეები არ არიან.');
  expect(screen.getByRole('heading', { name:'კლასის კოდი' })).toBeTruthy();
  expect(screen.getByRole('button', { name:'კოდის შექმნა' }).matches(':disabled')).toBe(true);
  const selector = screen.getByLabelText('დაკავშირებული მოსწავლის დამატება');
  fireEvent.change(selector, { target:{ value:'s1' } });
  fireEvent.click(screen.getByRole('button', { name:'დამატება' }));
  await screen.findByLabelText('სატესტო პირველი');
  expect(within(selector).queryByRole('option', { name:'სატესტო პირველი' })).toBeNull();
  fireEvent.change(selector, { target:{ value:'s2' } }); fireEvent.click(screen.getByRole('button', { name:'დამატება' }));
  await screen.findByLabelText('სატესტო მეორე');
  await waitFor(() => expect(room.textContent).toContain('2 მოსწავლე'));
  fireEvent.click(screen.getByLabelText('სატესტო პირველი'));
  fireEvent.click(screen.getByRole('button', { name:'ბარათების გადახედვა' }));
  await screen.findByRole('heading', { name:'ბარათების წინასწარი ნახვა' });
  let portal = document.querySelector('.classroom-print-document')!;
  expect(portal.textContent).toContain('სატესტო პირველი'); expect(portal.textContent).not.toContain('სატესტო მეორე');
  expect(portal.textContent).toContain('ანგარიშის სტატუსი უცნობია'); expect(portal.textContent).toContain('ადმინისტრატორს');
  expect(portal.textContent).not.toContain('s1'); expect(portal.textContent).not.toContain('s2');
  fireEvent.click(screen.getByRole('button', { name:'ბეჭდვა / PDF-ად შენახვა' }));
  await waitFor(() => expect(print).toHaveBeenCalledTimes(1));
  fireEvent(window, new Event('afterprint')); expect(document.body.classList.contains('axiom-cards-printing')).toBe(false);
  fireEvent.click(screen.getByRole('button', { name:'ყველას არჩევა' }));
  fireEvent.click(screen.getByRole('button', { name:'ბარათების გადახედვა' }));
  await screen.findByRole('heading', { name:'ბარათების წინასწარი ნახვა' });
  portal = document.querySelector('.classroom-print-document')!;
  expect(portal.querySelectorAll('.classroom-login-card')).toHaveLength(2);
  expect(portal.textContent).toContain('სატესტო პირველი'); expect(portal.textContent).toContain('სატესტო მეორე');
  const first = screen.getByLabelText('სატესტო პირველი').closest('li')!;
  fireEvent.click(within(first).getByRole('button', { name:'კლასიდან ამოღება' }));
  fireEvent.click(within(first).getByRole('button', { name:'არა' }));
  expect(screen.getByLabelText('სატესტო პირველი')).toBeTruthy();
  fireEvent.click(within(first).getByRole('button', { name:'კლასიდან ამოღება' }));
  fireEvent.click(within(first).getByRole('button', { name:'დიახ, ამოღება' }));
  await waitFor(() => expect(screen.queryByLabelText('სატესტო პირველი')).toBeNull());
  fireEvent.click(within(room).getByRole('button', { name:'არქივში გადატანა' }));
  fireEvent.click(within(room).getByRole('button', { name:'დიახ, დაარქივება' }));
  await waitFor(() => expect(room.textContent).toContain('დაარქივებული'));
  expect(screen.getByText('დაარქივებული კლასი მხოლოდ სანახავია.')).toBeTruthy();
  expect(screen.queryByRole('button', { name:'დამატება' })).toBeNull();
  unmount(); render(<Classrooms client={null} assigned={roster} test />);
  expect(await screen.findByText('კლასები ჯერ არ არის.')).toBeTruthy();
});
