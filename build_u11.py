# under noUnusedLocals; drop the unused binding before writing the file.
import re as _re
_clean = []
for _block in templates:
    def _fix(match, _b=_block):
        body = match.group(2)
        if 'vars.' in body or 'vars[' in body:
            return match.group(0)
        return f"{match.group(1)}explanation: ({{ answer }}) => `{body}`,"
    _clean.append(_re.sub(r"(\s*)explanation: \(\{ vars, answer \}\) => `(.*?)`,",
                          _fix, _block, flags=_re.S))
templates = _clean

